package org.tmt.aps.peas.camera.model;

public class FineTilt {
	private float x;
	private float y;

	FineTilt(float x, float y) {
		this.x = x;
		this.y = y;
	}
	
	public float getX() {
		return x;
	}

	public void setX(float x) {
		this.x = x;
	}

	public float getY() {
		return y;
	}

	public void setY(float y) {
		this.y = y;
	}

}